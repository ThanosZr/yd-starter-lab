import fs from 'node:fs';
import path from 'node:path';
const publicEdition=process.argv.includes('--public');
const edition=publicEdition?'PUBLIC — no quizzes':'FULL — 36 questions';
const copy=(src,dst)=>{fs.mkdirSync(path.dirname(dst),{recursive:true});fs.copyFileSync(src,dst)};
fs.rmSync('dist',{recursive:true,force:true});
for(const file of ['styles.css','vendor/react.production.min.js','vendor/react-dom.production.min.js','src/engine/topology.js','src/engine/motor-dynamics.js'])copy(file,path.join('dist',file));
fs.writeFileSync('dist/.nojekyll','');
let main=fs.readFileSync('src/main.js','utf8');
// The import remains in main, but public edition gets an EMPTY questions module.
main=main.replace("const HAS_QUIZ = typeof __HAS_QUIZ__==='undefined'?true:__HAS_QUIZ__;",`const HAS_QUIZ = ${!publicEdition};`);
fs.writeFileSync('dist/src/main.js',main);
const quiz=publicEdition?'export default [];\n':fs.readFileSync('src/quiz.js','utf8');
fs.writeFileSync('dist/src/quiz.js',quiz);
const css=fs.readFileSync('styles.css','utf8');
const vendor=fs.readFileSync('vendor/react.production.min.js','utf8')+'\n'+fs.readFileSync('vendor/react-dom.production.min.js','utf8');
const stripMod=source=>source.replace(/^export\s*\{[^}]*\}\s*;?\s*$/gm,'').replace(/^export\s+(?=(?:class|const|function|let|var)\b)/gm,'');
const engine=stripMod(fs.readFileSync('src/engine/topology.js','utf8'))+'\n'+stripMod(fs.readFileSync('src/engine/motor-dynamics.js','utf8'));
const q=quiz.replace(/^export\s+default\s+/,'const QUIZ = ');
const classicMain=main.split('\n').filter(line=>!/^(?:\s*)import\s/.test(line)).join('\n');
const boot=`window.addEventListener('error',function(e){const r=document.getElementById('root');if(r&&r.getAttribute('data-ready')!=='yes'){r.innerHTML='<div style="padding:28px;background:#15263b;color:#fff;font:16px sans-serif"><b>YD LAB: Σφάλμα εκκίνησης</b><p>'+String(e.message).replace(/[<>&]/g,'')+'</p></div>';}});`;
const scripts=engine+'\n'+q+'\n'+classicMain+'\n'+`document.getElementById('root').setAttribute('data-ready','yes');`;
if (/^\s*(?:export|import)\s/m.test(scripts))throw Error('Standalone bundle contains ES module syntax');
const html=`<!doctype html><html lang="el"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,user-scalable=yes"><meta name="theme-color" content="#08121f"><title>YD LAB v3.0 — ${edition}</title><style>${css}</style></head><body><div id="root"><div style="padding:24px;color:#e7f5ff;background:#0c1829;font-family:system-ui">Φόρτωση YD LAB…</div></div><script>${boot}</script><script>${vendor}</script><script>${scripts}</script></body></html>`;
fs.writeFileSync('index.html',html);
fs.writeFileSync('standalone.html',html);
fs.writeFileSync('dist/index.html',html);
fs.writeFileSync('dist/standalone.html',html);
const moduleHtml=fs.readFileSync('index.module.html','utf8').replace(/v2\.2/g,'v3.0').replace(' και ερωτήσεις εξάσκησης',' και προσομοίωση ασύγχρονου κινητήρα');
fs.writeFileSync('dist/index.module.html',moduleHtml);
console.log(`Built YD LAB v3.0 ${edition}, offline file:// index.html and GitHub Pages.`);
